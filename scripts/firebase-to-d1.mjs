#!/usr/bin/env node
// firebase-to-d1.mjs — turn the old Firebase data into seed.sql for D1.
//
// Keeps each Firebase uid as users.id, so designs keep pointing at the right
// owner. Firebase password hashes (modified scrypt) can't be checked by the
// Worker, so migrated email/password users get password_hash = NULL: they
// can sign in with Google (same email) and the account is theirs again.
// Google users keep working because google_sub is copied over.
//
// 1) Export the users (Firebase CLI, logged in to the project):
//      npx firebase-tools auth:export scripts/firebase-export/users.json --format=json --project mud-magic-507ea
//
// 2) Designs come from Firestore. Either
//    a) let this script read them with a service-account key
//       (Firebase Console → Project settings → Service accounts → Generate key;
//       keep the file OUT of git — firebase-service-account*.json is ignored):
//         npm install --no-save firebase-admin
//         node scripts/firebase-to-d1.mjs --users scripts/firebase-export/users.json \
//              --service-account firebase-service-account.json
//    b) or pass a JSON file you exported yourself:
//         [{"id": "...", "ownerId": "...", "name": "...", "description": "...",
//           "createdAt": "2026-01-01T00:00:00Z", "updatedAt": "..."}, ...]
//         node scripts/firebase-to-d1.mjs --users ... --designs designs.json
//
// 3) Load it (local first to check, then the real database):
//      npx wrangler d1 execute mud-magic-db --local  --file seed.sql
//      npx wrangler d1 execute mud-magic-db --remote --file seed.sql
//
// Output goes to seed.sql (git-ignored) unless --out says otherwise.
// It only uses INSERT OR IGNORE, so running it twice is harmless.

import { readFile, writeFile } from "node:fs/promises";

function args() {
  const out = {};
  const argv = process.argv.slice(2);
  for (let i = 0; i < argv.length; i++) {
    if (argv[i].startsWith("--")) out[argv[i].slice(2)] = argv[i + 1]?.startsWith("--") ? true : argv[++i];
  }
  return out;
}

const sql = (v) => (v === null || v === undefined ? "NULL" : `'${String(v).replace(/'/g, "''")}'`);

function iso(value) {
  if (!value) return null;
  if (typeof value === "object" && typeof value.toDate === "function") return value.toDate().toISOString();
  if (typeof value === "object" && "_seconds" in value) return new Date(value._seconds * 1000).toISOString();
  if (typeof value === "object" && "seconds" in value) return new Date(value.seconds * 1000).toISOString();
  const n = Number(value);
  const d = Number.isFinite(n) && String(value).trim() !== "" ? new Date(n) : new Date(value);
  return Number.isNaN(d.getTime()) ? null : d.toISOString();
}

async function loadDesigns(opts) {
  if (opts.designs) return JSON.parse(await readFile(opts.designs, "utf8"));
  if (!opts["service-account"]) return [];
  let admin;
  try {
    admin = (await import("firebase-admin")).default;
  } catch {
    throw new Error("firebase-admin is not installed. Run: npm install --no-save firebase-admin");
  }
  const key = JSON.parse(await readFile(opts["service-account"], "utf8"));
  admin.initializeApp({ credential: admin.credential.cert(key) });
  const snap = await admin.firestore().collection("designs").get();
  return snap.docs.map((doc) => ({ id: doc.id, ...doc.data() }));
}

async function main() {
  const opts = args();
  if (!opts.users) {
    console.error("Usage: node scripts/firebase-to-d1.mjs --users users.json [--service-account key.json | --designs designs.json] [--out seed.sql]");
    process.exit(1);
  }
  const exported = JSON.parse(await readFile(opts.users, "utf8"));
  const users = Array.isArray(exported) ? exported : exported.users || [];
  const lines = ["-- Generated by scripts/firebase-to-d1.mjs — Firebase users and designs for D1.", ""];
  const known = new Set();
  let skipped = 0;

  for (const u of users) {
    if (!u.localId || !u.email) {
      skipped++;
      continue;
    }
    const google = (u.providerUserInfo || []).find((p) => p.providerId === "google.com");
    const email = String(u.email).toLowerCase();
    const name = (u.displayName || email.split("@")[0]).slice(0, 60);
    known.add(u.localId);
    lines.push(
      `INSERT OR IGNORE INTO users (id, email, password_hash, google_sub, display_name, photo_url, created_at) VALUES (${[
        sql(u.localId),
        sql(email),
        "NULL",
        sql(google ? google.rawId : null),
        sql(name),
        sql(u.photoUrl || (google && google.photoUrl) || ""),
        sql(iso(u.createdAt) || new Date().toISOString()),
      ].join(", ")});`
    );
  }

  const designs = await loadDesigns(opts);
  let orphans = 0;
  lines.push("");
  for (const d of designs) {
    if (!known.has(d.ownerId)) {
      orphans++;
      continue;
    }
    const created = iso(d.createdAt) || new Date().toISOString();
    const config = typeof d.description === "string" ? d.description : JSON.stringify(d.description ?? null);
    lines.push(
      `INSERT OR IGNORE INTO designs (id, user_id, name, config, created_at, updated_at) VALUES (${[
        sql(d.id),
        sql(d.ownerId),
        sql(String(d.name || "Ceramic design").slice(0, 150)),
        sql(config),
        sql(created),
        sql(iso(d.updatedAt) || created),
      ].join(", ")});`
    );
  }

  const out = opts.out || "seed.sql";
  await writeFile(out, lines.join("\n") + "\n", "utf8");
  console.log(`Wrote ${out}: ${known.size} users, ${designs.length - orphans} designs.`);
  if (skipped) console.log(`Skipped ${skipped} users without an email.`);
  if (orphans) console.log(`Skipped ${orphans} designs whose owner isn't in the users export.`);
  process.exit(0);
}

main().catch((err) => {
  console.error(err.message || err);
  process.exit(1);
});
